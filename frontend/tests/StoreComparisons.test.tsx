import {cleanup,fireEvent,render,screen,waitFor} from '@testing-library/react';
import {afterEach,expect,it,vi} from 'vitest';
import {StoreAnalyticsReportPage} from '../src/pages/StoreAnalyticsReportPage';
import {SalesDynamicsReportPage} from '../src/pages/SalesDynamicsReportPage';
vi.mock('recharts',()=>{const Box=({children}:any)=><div>{children}</div>;return {ResponsiveContainer:Box,BarChart:({children,data,layout}:any)=><div data-testid="bars" data-layout={layout} data-values={JSON.stringify(data)}>{children}</div>,Bar:({name}:any)=><span data-testid="bar">{name}</span>,LineChart:Box,Line:()=>null,CartesianGrid:()=>null,Legend:()=>null,Tooltip:()=>null,XAxis:()=>null,YAxis:()=>null};});
afterEach(()=>{cleanup();vi.unstubAllGlobals();});
it('preloads both store comparisons and changes vertical bars and cards locally',async()=>{
 const period={start:'2026-09-01',end:'2026-09-30'};
 const metrics=(previous:number)=>Object.fromEntries(['revenue','checks','average_check','items','items_per_check','average_discount'].map(key=>[key,{current:100,previous,difference:100-previous,change_percent:100}]));
 const comparison=(previous:number)=>({period,metrics:metrics(previous),stores:[{store:'Магазин',metrics:metrics(previous)}]});
 const previous=comparison(20),year=comparison(50);
 const fetch=vi.fn(async(url:string)=>new Response(JSON.stringify(url.includes('/filters')?{departments:[]}:url.includes('/reports/store-analytics?')?{period,previous_period:period,metrics:previous.metrics,stores:previous.stores,comparisons:{previous_period:previous,previous_year:year}}:[])));
 vi.stubGlobal('fetch',fetch);render(<StoreAnalyticsReportPage/>);
 expect(screen.queryByRole('button',{name:'Прошлый год'})).toBeNull();
 const checkboxes=screen.getByRole('group',{name:'Отображать сравнения'});
 expect(checkboxes.previousElementSibling?.classList.contains('analytics-build-actions')).toBe(true);
 fireEvent.click(screen.getByRole('button',{name:'Сформировать отчёт'}));
 await screen.findByTestId('bars');
 expect(screen.getByTestId('bars').getAttribute('data-layout')).toBe('horizontal');
 expect(JSON.parse(screen.getByTestId('bars').getAttribute('data-values')!)[0]).toMatchObject({current:100,previous:20,year:50});
 expect(screen.getAllByTestId('bar')).toHaveLength(3);
 fireEvent.click(screen.getByRole('checkbox',{name:'Предыдущий период'}));expect(screen.getAllByTestId('bar')).toHaveLength(2);
 fireEvent.click(screen.getByRole('checkbox',{name:'Прошлый год'}));expect(screen.getAllByTestId('bar')).toHaveLength(1);
 fireEvent.click(screen.getByRole('checkbox',{name:'Предыдущий период'}));fireEvent.click(screen.getByRole('checkbox',{name:'Прошлый год'}));
 expect(screen.getAllByTestId('bar')).toHaveLength(3);
 expect(screen.queryByText(/Параметры изменены/)).toBeNull();
 const calls=fetch.mock.calls.filter(([url])=>url.includes('/reports/store-analytics?'));
 expect(calls).toHaveLength(1);expect(calls[0][0]).toContain('include_both=true');
});
it.each([StoreAnalyticsReportPage,SalesDynamicsReportPage])('selects the calendar year without requesting until Generate',async(Page)=>{
 const fetch=vi.fn(async(url:string)=>url.includes('/reports/')?new Response(JSON.stringify({detail:'Тестовая остановка'}),{status:503}):new Response(JSON.stringify(url.includes('/filters')?{departments:[]}:[])));
 vi.stubGlobal('fetch',fetch);render(<Page/>);
 fireEvent.click(screen.getByRole('button',{name:'Год'}));
 expect(screen.getByRole('button',{name:'Год'}).className).toBe('active');
 expect(fetch.mock.calls.filter(([url])=>/\/reports\/(store-analytics|sales-dynamics)\?/.test(url))).toHaveLength(0);
 fireEvent.click(screen.getByRole('button',{name:'Сформировать отчёт'}));
 await waitFor(()=>expect(fetch.mock.calls.some(([url])=>url.includes('period_kind=year'))).toBe(true));
 const url=fetch.mock.calls.find(([url])=>url.includes('period_kind=year'))![0];
 expect(new URL(url,'http://test').searchParams.get('date_from')).toBe(`${new Date().getFullYear()}-01-01`);
});
